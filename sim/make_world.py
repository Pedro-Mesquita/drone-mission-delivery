"""Writes the Gazebo worlds of the delivery mission.

    make_world.py                      reference track (worlds/cartolinas_track.sdf)
    make_world.py fixed [NAME ...]     fixed scenarios of scenarios.py (all by default)
    make_world.py random --seed N --count K [--land]

Each scenario writes worlds/<name>.sdf, its textures and meshes in
assets/<name>/, and worlds/<name>.json with the track, the target and the
mission command line. Only the reference track is kept in git.

Cartolinas are given in NED meters from the takeoff point; the Gazebo world
is ENU (x = east, y = north), as the ArduPilot plugin expects.

Scenario textures and shapes come from the drone-ml-project dataset
generator (datagen/textures.py and datagen/shapes.py), found through
ML_DATAGEN (default: ../../drone-ml-project/datagen from this file).
Run with the mission's Python (it uses the mission's planner):
    .venv/bin/python sim/make_world.py fixed
"""

import argparse
import dataclasses
import importlib
import json
import math
import os
import sys
from pathlib import Path
from types import ModuleType

sys.path.insert(0, str(Path(__file__).resolve().parent))

from scenarios import Scenario, fixed_scenarios, random_scenario

from mission_delivery.config import PlannerConfig

SIZE_NORTH, SIZE_EAST = 0.66, 0.5

# name, north, east, yaw (degrees clockwise from north), RGB
CARTOLINAS = [
    ("right", 8.0, 1.0, 0.0, "0.85 0.1 0.1"),
    ("left", 15.0, -1.0, 30.0, "0.1 0.25 0.85"),
    ("gap_left", 22.0, -2.2, 0.0, "0.95 0.8 0.1"),
    ("gap_right", 22.0, 2.2, 0.0, "0.1 0.7 0.2"),
]

HEADER_TEMPLATE = """<?xml version="1.0" ?>
<sdf version="1.9">
{comment}
  <world name="cartolinas_track">
    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>

    <scene>
      <ambient>1.0 1.0 1.0</ambient>
      <background>0.8 0.8 0.8</background>
      <sky></sky>
    </scene>

    <spherical_coordinates>
      <latitude_deg>-35.363262</latitude_deg>
      <longitude_deg>149.165237</longitude_deg>
      <elevation>584</elevation>
      <heading_deg>0</heading_deg>
      <surface_model>EARTH_WGS84</surface_model>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.8 0.8 0.8 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <include>
      <uri>model://runway</uri>
      <pose degrees="true">-29 545 0 0 0 363</pose>
    </include>
"""

REFERENCE_COMMENT = """  <!--
    Reference track of the delivery mission: a cartolina on the right of the
    straight line (north 8 m), one on the left (north 15 m), and two leaving
    a single passage (north 22 m). Target: north 28 m, east 0.
    Generated by make_world.py: edit that file, not this one.
  -->"""

FOOTER = """
    <include>
      <uri>model://iris_downcam</uri>
      <pose degrees="true">0 0 0.195 0 0 90</pose>
    </include>
  </world>
</sdf>
"""


def cartolina(name: str, north: float, east: float, yaw: float, rgb: str) -> str:
    return f"""
    <model name="cartolina_{name}">
      <static>true</static>
      <pose>{east} {north} 0.002 0 0 {math.radians(-yaw):.6f}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><box><size>{SIZE_EAST} {SIZE_NORTH} 0.002</size></box></geometry>
          <material>
            <ambient>{rgb} 1</ambient>
            <diffuse>{rgb} 1</diffuse>
            <specular>0.1 0.1 0.1 1</specular>
          </material>
        </visual>
      </link>
    </model>"""


def header(comment: str) -> str:
    # str.replace, not str.format: the SDF has no braces but keep it literal anyway.
    return HEADER_TEMPLATE.replace("{comment}", comment)


def write_reference() -> Path:
    body = "".join(cartolina(*item) for item in CARTOLINAS)
    path = Path(__file__).parent / "worlds" / "cartolinas_track.sdf"
    path.write_text(header(REFERENCE_COMMENT) + body + FOOTER, encoding="utf-8")
    return path


# ---------------------------------------------------------------- scenarios

SIM_DIR = Path(__file__).resolve().parent
GROUND_TILE = 8.0  # meters per repetition of the ground texture
GROUND_MARGIN = 10.0  # meters of textured ground around the track


def _datagen() -> tuple[ModuleType, ModuleType]:
    default = SIM_DIR.parent.parent / "drone-ml-project" / "datagen"
    path = Path(os.environ.get("ML_DATAGEN", default))
    if not (path / "textures.py").exists():
        sys.exit(f"ML_DATAGEN: no textures.py in {path}; point it to drone-ml-project/datagen")
    sys.path.insert(0, str(path))
    return importlib.import_module("textures"), importlib.import_module("shapes")


def flat_mesh(name: str, mesh: Path, texture: Path, north: float, east: float, z: float,
              yaw_deg: float, scale_east: float, scale_north: float) -> str:
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{east:.4f} {north:.4f} {z} 0 0 {math.radians(-yaw_deg):.6f}</pose>
      <link name="link">
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <geometry><mesh><uri>{mesh}</uri>
            <scale>{scale_east:.4f} {scale_north:.4f} 1</scale></mesh></geometry>
          <material>
            <ambient>1 1 1 1</ambient>
            <diffuse>1 1 1 1</diffuse>
            <specular>0.1 0.1 0.1 1</specular>
            <pbr><metal><albedo_map>{texture}</albedo_map><roughness>0.9</roughness><metalness>0</metalness></metal></pbr>
          </material>
        </visual>
      </link>
    </model>"""


def write_scenario(scenario: Scenario) -> Path:
    import numpy as np

    textures, shapes = _datagen()
    assets = SIM_DIR / "assets" / scenario.name
    assets.mkdir(parents=True, exist_ok=True)
    square = assets / "square.obj"
    shapes.write_obj(square, shapes.unit_square())

    body = []
    if scenario.ground is not None:
        track = scenario.track
        north_lo = min(p.north for p in track) - GROUND_MARGIN
        north_hi = max(p.north for p in track) + GROUND_MARGIN
        east_lo = min(p.east for p in track) - GROUND_MARGIN
        east_hi = max(p.east for p in track) + GROUND_MARGIN
        size = max(north_hi - north_lo, east_hi - east_lo)
        ground_mesh = assets / "ground.obj"
        shapes.write_obj(ground_mesh, shapes.unit_square() * size, uv_repeat=size / GROUND_TILE)
        ground_png = assets / "ground.png"
        rng = np.random.default_rng([scenario.ground_seed, 7])
        textures.save_png(ground_png, textures.ground_texture(rng, scenario.ground))
        body.append(flat_mesh("ground", ground_mesh, ground_png, (north_lo + north_hi) / 2,
                              (east_lo + east_hi) / 2, 0.001, 0.0, 1.0, 1.0))

    for index, item in enumerate(scenario.cartolinas):
        png = assets / f"cartolina_{index:02d}.png"
        if item.rgb is not None:
            image = np.ones((64, 64, 3)) * np.array(item.rgb)
        else:
            image, _ = textures.object_texture(np.random.default_rng(item.texture_seed),
                                               item.family, False)
        textures.save_png(png, image)
        body.append(flat_mesh(f"cartolina_{index:02d}", square, png, item.north, item.east,
                              0.003, item.yaw, item.width, item.length))

    for index, shape in enumerate(scenario.distractors):
        rng = np.random.default_rng(shape.shape_seed)
        mesh = assets / f"distractor_{index:02d}.obj"
        shapes.write_obj(mesh, shapes.random_negative(rng, shape.kind))
        png = assets / f"distractor_{index:02d}.png"
        image, _ = textures.object_texture(rng, str(rng.choice(["solid", "paper"])), False)
        textures.save_png(png, image)
        body.append(flat_mesh(f"distractor_{index:02d}", mesh, png, item.north, item.east,
                              0.003, shape.yaw, shape.size, shape.size))

    track_args = " ".join(f"{p.north:g} {p.east:g}" for p in scenario.track)
    target = scenario.target
    command = (f"python -m mission_delivery.mission --target {target.north:g} {target.east:g} "
               f"--track {track_args} --base-url http://127.0.0.1:8020")
    width = 2 * scenario.half_width
    comment = f"""  <!--
    Scenario {scenario.name}: {scenario.description}.
    Track {width:.1f} m wide, target north {target.north:g} m, east {target.east:g} m.
    Expected: {scenario.expect}. Generated by make_world.py.
  -->"""
    world = SIM_DIR / "worlds" / f"{scenario.name}.sdf"
    text = header(comment)
    if scenario.sun is not None:
        text = text.replace("<direction>-0.5 0.1 -0.9</direction>",
                            "<direction>{} {} {}</direction>".format(*scenario.sun))
    world.write_text(text + "".join(body) + FOOTER, encoding="utf-8")

    info = {
        "name": scenario.name,
        "description": scenario.description,
        "expect": scenario.expect,
        "width": round(width, 3),
        "track": [[p.north, p.east] for p in scenario.track],
        "target": [target.north, target.east],
        "planner": dataclasses.asdict(PlannerConfig()),
        "cartolinas": [dataclasses.asdict(c) for c in scenario.cartolinas],
        "distractors": [dataclasses.asdict(d) for d in scenario.distractors],
        "ground": scenario.ground,
        "sun": scenario.sun,
        "mission_command": command,
    }
    world.with_suffix(".json").write_text(json.dumps(info, indent=1, ensure_ascii=False),
                                          encoding="utf-8")
    return world


def main() -> None:
    parser = argparse.ArgumentParser(description="Writes the delivery mission's Gazebo worlds.")
    sub = parser.add_subparsers(dest="kind")
    fixed = sub.add_parser("fixed", help="fixed scenarios")
    fixed.add_argument("names", nargs="*", help="scenario names (default: all)")
    rand = sub.add_parser("random", help="seeded random scenario")
    rand.add_argument("--seed", type=int, required=True)
    rand.add_argument("--count", type=int, default=7, help="number of cartolinas")
    rand.add_argument("--land", action="store_true", help="one step too narrow: no path")
    args = parser.parse_args()

    if args.kind is None:
        print(write_reference())
        return
    if args.kind == "fixed":
        chosen = [s for s in fixed_scenarios() if not args.names or s.name in args.names]
        unknown = set(args.names) - {s.name for s in chosen}
        if unknown:
            parser.error(f"unknown scenarios: {', '.join(sorted(unknown))}")
    else:
        chosen = [random_scenario(args.seed, args.count,
                                  expect="land" if args.land else "deliver")]
    for scenario in chosen:
        world = write_scenario(scenario)
        print(f"{world}  ({2 * scenario.half_width:.1f} m, {len(scenario.cartolinas)} "
              f"cartolinas, expect {scenario.expect})")
        print(f"  WORLD={scenario.name} sim/run_sim.sh")
        print(f"  {json.loads(world.with_suffix('.json').read_text())['mission_command']}")


if __name__ == "__main__":
    main()
