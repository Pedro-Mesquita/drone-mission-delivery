"""Writes worlds/cartolinas_track.sdf, the reference track of the delivery mission.

Cartolinas are given in NED meters from the takeoff point; the Gazebo world
is ENU (x = east, y = north), as the ArduPilot plugin expects.
"""

import math
from pathlib import Path

SIZE_NORTH, SIZE_EAST = 0.66, 0.5

# name, north, east, yaw (degrees clockwise from north), RGB
CARTOLINAS = [
    ("right", 8.0, 1.0, 0.0, "0.85 0.1 0.1"),
    ("left", 15.0, -1.0, 30.0, "0.1 0.25 0.85"),
    ("gap_left", 22.0, -2.2, 0.0, "0.95 0.8 0.1"),
    ("gap_right", 22.0, 2.2, 0.0, "0.1 0.7 0.2"),
]

HEADER = """<?xml version="1.0" ?>
<sdf version="1.9">
  <!--
    Reference track of the delivery mission: a cartolina on the right of the
    straight line (north 8 m), one on the left (north 15 m), and two leaving
    a single passage (north 22 m). Target: north 28 m, east 0.
    Generated by make_world.py: edit that file, not this one.
  -->
  <world name="cartolinas_track">
    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>

    <scene>
      <ambient>1.0 1.0 1.0</ambient>
      <background>0.8 0.8 0.8</background>
      <sky></sky>
    </scene>

    <spherical_coordinates>
      <latitude_deg>-35.363262</latitude_deg>
      <longitude_deg>149.165237</longitude_deg>
      <elevation>584</elevation>
      <heading_deg>0</heading_deg>
      <surface_model>EARTH_WGS84</surface_model>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.8 0.8 0.8 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <include>
      <uri>model://runway</uri>
      <pose degrees="true">-29 545 0 0 0 363</pose>
    </include>
"""

FOOTER = """
    <include>
      <uri>model://iris_downcam</uri>
      <pose degrees="true">0 0 0.195 0 0 90</pose>
    </include>
  </world>
</sdf>
"""


def cartolina(name: str, north: float, east: float, yaw: float, rgb: str) -> str:
    return f"""
    <model name="cartolina_{name}">
      <static>true</static>
      <pose>{east} {north} 0.002 0 0 {math.radians(-yaw):.6f}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><box><size>{SIZE_EAST} {SIZE_NORTH} 0.002</size></box></geometry>
          <material>
            <ambient>{rgb} 1</ambient>
            <diffuse>{rgb} 1</diffuse>
            <specular>0.1 0.1 0.1 1</specular>
          </material>
        </visual>
      </link>
    </model>"""


def main() -> None:
    body = "".join(cartolina(*item) for item in CARTOLINAS)
    path = Path(__file__).parent / "worlds" / "cartolinas_track.sdf"
    path.write_text(HEADER + body + FOOTER, encoding="utf-8")
    print(path)


if __name__ == "__main__":
    main()
